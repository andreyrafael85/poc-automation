const FULL_CLIP = /<defs><clipPath id="[^"]+"><rect width="20" height="20"><\/rect><\/clipPath><\/defs>$/;

function pathsOf(name, body) {
  let inner = body.trim();
  if (FULL_CLIP.test(inner)) {
    inner = inner.replace(FULL_CLIP, '').trim();
    const group = /^<g>(.*)<\/g>$/s.exec(inner);
    if (group === null) throw new Error(`${name}: clipped glyph without a single group`);
    inner = group[1];
  }
  const rest = inner.replace(/<path d="[^"]+"><\/path>/g, '').trim();
  if (rest !== '') throw new Error(`${name}: not only paths (${rest.slice(0, 60)}…)`);
  return [...inner.matchAll(/<path d="([^"]+)"><\/path>/g)].map((match) => match[1]);
}

const html = fs.readFileSync(GALLERY, 'utf8');
const gallery = new Map(
  [...html.matchAll(/<svg[^>]*viewBox="0 0 20 20" data-iconname="([^"]+)"[^>]*>(.*?)<\/svg>/gs)].map((match) => [
    match[1],
    match[2],
  ]),
);

const lines = [
  '/**',
  ' * Brand glyphs from the Dynatrace third-party icon gallery (monochrome, `currentColor`, 20×20).',
  ' *',
  ' * Use only icons you are entitled to use. Generated by `scripts/gen-brand-glyphs.cjs` from the',
  ' * gallery page; do not edit by hand. Each key names the gallery icon it was copied from.',
  ' */',
  '',
  'export const BRAND_GLYPHS = {',
];
for (const [key, icon] of Object.entries(GLYPHS)) {
  const body = gallery.get(icon);
  if (body === undefined) throw new Error(`${icon} is not in the gallery`);
  lines.push(`  // ${icon}`);
  lines.push(`  ${key}: [`);
  for (const d of pathsOf(icon, body)) lines.push(`    '${d}',`);
  lines.push('  ],');
}
lines.push('} as const satisfies Record<string, readonly string[]>;', '', 'export type BrandGlyph = keyof typeof BRAND_GLYPHS;', '');

fs.writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${Object.keys(GLYPHS).length} glyphs to ${path.relative(process.cwd(), OUT)}`);
