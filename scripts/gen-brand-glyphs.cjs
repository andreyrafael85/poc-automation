// Build-time generator (not shipped). Copies the third-party glyphs the app uses from the
// Dynatrace icon gallery (developer.dynatracelabs.com → Design → Icons → Third-party icons) into
// `ui/app/components/spectrum/brandGlyphs.ts`.
//
// The gallery draws every glyph on a 20×20 grid in `currentColor`. A few wrap their paths in a
// group clipped to the full 20×20 square, which clips nothing; those paths are taken as they are.
// A glyph built from anything other than paths is refused rather than half-copied.
//
// Usage (from the app root):
//   node scripts/gen-brand-glyphs.cjs [path/to/third-party-icons/index.html]
const fs = require('fs');
const path = require('path');

const GALLERY = process.argv[2];
if (!GALLERY) {
  console.error('usage: node scripts/gen-brand-glyphs.cjs <path/to/third-party-icons/index.html>');
  process.exit(2);
}
const OUT = path.join(__dirname, '..', 'ui', 'app', 'components', 'spectrum', 'brandGlyphs.ts');

