// Build-time asset generator (not shipped). Rasterises the AWS / Azure / GCP
// brand SVGs to compact PNG data URLs and emits a TS module the Cloud page and
// the reports import. Run with Node from the app root:
//   node scripts/gen-cloud-logos.cjs
// Source SVGs live in ~/dynatrace-brand/logos-cloud (or $DT_BRAND_DIR/logos-cloud).
const fs = require('fs');
const path = require('path');
const { Resvg } = require('@resvg/resvg-js');

const SRC = path.join(process.env.DT_BRAND_DIR ?? path.join(require('os').homedir(), 'dynatrace-brand'), 'logos-cloud');
const OUT = path.join(__dirname, '..', 'ui', 'app', 'models', 'cloudLogos.ts');

// Colour marks, shown on a white chip in the UI so they read on light and dark.
const LOGOS = {
  AWS: 'Amazon_Web_Services_Logo.svg',
  Azure: 'microsoft-azure.svg',
  GCP: 'Google Cloud GCP.svg',
};

function raster(file, height) {
  const svg = fs.readFileSync(path.join(SRC, file));
  const r = new Resvg(svg, { fitTo: { mode: 'height', value: height } });
  return 'data:image/png;base64,' + r.render().asPng().toString('base64');
}

const entries = Object.entries(LOGOS).map(
  ([key, file]) => `  ${key}: '${raster(file, 64)}',`,
);

const banner = `/* eslint-disable */
/**
 * Cloud provider brand logomarks as compact PNG data URLs.
 *
 * Generated by scripts/gen-cloud-logos.cjs from the official SVGs in
 * the brand kit's logos-cloud folder. Colour marks, meant to sit on a
 * white chip so they read on both light and dark backgrounds. Re-run the script
 * if the source SVGs change. Do not edit by hand.
 */
`;

const body = `${banner}export const CLOUD_LOGOS = {\n${entries.join('\n')}\n} as const;\n\nexport type CloudLogoKey = keyof typeof CLOUD_LOGOS;\n`;

fs.writeFileSync(OUT, body);
console.log('Wrote', OUT, `(${(body.length / 1024).toFixed(1)} kB)`);
